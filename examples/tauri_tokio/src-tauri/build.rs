fn main() {
    ensure_icon();
    tauri_build::build();
}

fn ensure_icon() {
    let manifest_dir = std::path::PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let icon_dir = manifest_dir.join("icons");
    let icon_path = icon_dir.join("icon.ico");
    if icon_path.exists() {
        return;
    }

    if std::fs::create_dir_all(&icon_dir).is_err() {
        return;
    }

    let png_bytes: [u8; 67] = [
        0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A, 0x00, 0x00, 0x00, 0x0D, 0x49,
        0x48, 0x44, 0x52, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01, 0x08, 0x06,
        0x00, 0x00, 0x00, 0x1F, 0x15, 0xC4, 0x89, 0x00, 0x00, 0x00, 0x0A, 0x49, 0x44,
        0x41, 0x54, 0x78, 0x9C, 0x63, 0x00, 0x01, 0x00, 0x00, 0x05, 0x00, 0x01, 0x0D,
        0x0A, 0x2D, 0xB4, 0x00, 0x00, 0x00, 0x00, 0x49, 0x45, 0x4E, 0x44, 0xAE, 0x42,
        0x60, 0x82,
    ];

    let mut ico_bytes = Vec::with_capacity(6 + 16 + png_bytes.len());
    ico_bytes.extend_from_slice(&[0x00, 0x00, 0x01, 0x00, 0x01, 0x00]);
    ico_bytes.extend_from_slice(&[
        0x01, 0x01, 0x00, 0x00, 0x01, 0x00, 0x20, 0x00, 0x43, 0x00, 0x00, 0x00, 0x16,
        0x00, 0x00, 0x00,
    ]);
    ico_bytes.extend_from_slice(&png_bytes);

    let _ = std::fs::write(icon_path, ico_bytes);
}
